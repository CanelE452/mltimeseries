def build_dir_inventory() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for root in (Path("experiments"), Path("results")):
        if not root.exists():
            continue
        for path in sorted(p for p in root.glob("peft_*") if p.is_dir()):
            entry = DIR_COVERAGE_BY_NAME.get(path.name)
            if entry is None:
                entry = {
                    "mapped_exposure_units": "UNKNOWN",
                    "coverage_status": "[미검증] explicit_unknown_no_mapping_in_audit_script",
                    "source_range_summary": "UNKNOWN",
                    "evidence_refs": "UNKNOWN",
                    "notes": "[미검증] Directory exists locally but was not mapped to an exposure unit by this audit.",
                }
            rows.append(
                {
                    "evidence_status": entry["coverage_status"].split()[0],
                    "peft_dir": path.as_posix(),
                    "dir_kind": root.name,
                    "mapped_exposure_units": entry["mapped_exposure_units"],
                    "coverage_status": entry["coverage_status"],
                    "source_range_summary": entry["source_range_summary"],
                    "evidence_refs": entry["evidence_refs"],
                    "notes": entry["notes"],
                }
            )
    return rows


