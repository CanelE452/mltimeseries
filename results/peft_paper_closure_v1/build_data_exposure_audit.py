def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    ledger_path = OUT_DIR / "data_exposure_ledger.csv"
    with ledger_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(ROWS[0].keys()))
        writer.writeheader()
        writer.writerows(ROWS)

    (OUT_DIR / "holdout_availability.json").write_text(
        json.dumps(AVAILABILITY, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    dir_inventory = build_dir_inventory()
    inventory_path = OUT_DIR / "data_exposure_dir_inventory.csv"
    with inventory_path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(dir_inventory[0].keys()))
        writer.writeheader()
        writer.writerows(dir_inventory)
    (OUT_DIR / "data_exposure_dir_inventory.json").write_text(
        json.dumps(dir_inventory, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    (OUT_DIR / "holdout_availability.md").write_text(build_availability_md(), encoding="utf-8")
    (OUT_DIR / "data_exposure_audit.md").write_text(build_markdown(), encoding="utf-8")


if __name__ == "__main__":
    main()
